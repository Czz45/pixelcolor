package com.example.pixelcolor.engine

object SpriteTemplates {

    data class Template(val name: String, val width: Int, val height: Int, val data: String) {
        fun toCanvas(): PixelCanvas {
            val cells = Array(height) { y ->
                IntArray(width) { x ->
                    data[y * width + x].digitToIntOrNull() ?: 0
                }
            }
            val filled = Array(height) { BooleanArray(width) { false } }
            val fillOrder = Array(height) { IntArray(width) { 0 } }
            return PixelCanvas(width, height, cells, filled, fillOrder)
        }
    }

